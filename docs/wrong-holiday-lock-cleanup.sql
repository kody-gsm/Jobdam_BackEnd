-- 휴업일이 아닌 날에 잘못 만들어진 잠금(LOCKED) 정리
--
-- 나이스는 휴업일이 아닌 날의 휴업일 구분(SBTR_DD_SC_NM)에 '해당없음'을 넣는다.
-- 이 값을 휴업일로 잘못 읽어서, 학사일정이 있는 평일(입학설명회 등)까지 잠갔다.
-- 코드는 fix/neis-holiday-type 에서 고쳤고, 이미 만들어진 행만 아래로 지운다.
--
-- 아래 날짜는 2026-09-15 ~ 2026-11-30 구간에서 '해당없음' 일정만 있는 평일이다.
-- 다른 기간을 정리하려면 나이스 응답을 다시 확인해 날짜를 바꾼다.
-- 주의: 같은 날짜에 선생님이 직접 잠근 시간이 있으면 그것도 함께 지워진다. 필요하면 다시 잠가야 한다.

-- 1) 지울 행 확인 (날짜별 건수)
SELECT 'course' AS t, date, COUNT(*) AS locked_rows FROM course
WHERE state = 'LOCKED'
  AND date IN ('2026-09-16','2026-10-01','2026-10-02','2026-10-19','2026-10-20','2026-10-21','2026-10-22',
               '2026-10-27','2026-10-30','2026-11-02','2026-11-03','2026-11-04','2026-11-05','2026-11-06',
               '2026-11-13','2026-11-19')
GROUP BY date
UNION ALL
SELECT 'common', date, COUNT(*) FROM common
WHERE state = 'LOCKED'
  AND date IN ('2026-09-16','2026-10-01','2026-10-02','2026-10-19','2026-10-20','2026-10-21','2026-10-22',
               '2026-10-27','2026-10-30','2026-11-02','2026-11-03','2026-11-04','2026-11-05','2026-11-06',
               '2026-11-13','2026-11-19')
GROUP BY date;

